create or replace function public.ram_is_admin()
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select coalesce(
    (auth.jwt() -> 'app_metadata' ->> 'ram_role') = 'admin',
    false
  );
$$;

revoke all on function public.ram_is_admin() from public;
grant execute on function public.ram_is_admin() to anon, authenticated;

create or replace function public.ram_ensure_brand(p_name text)
returns public.ram_brands
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text := nullif(trim(p_name), '');
  v_row public.ram_brands;
begin
  if v_name is null then
    raise exception 'El nombre de la marca es obligatorio';
  end if;
  if not public.ram_is_admin() then
    raise exception 'No autorizado';
  end if;

  select * into v_row
  from public.ram_brands
  where lower(name) = lower(v_name)
  limit 1;

  if found then
    if v_row.active is distinct from true then
      update public.ram_brands
      set active = true, updated_at = now()
      where id = v_row.id
      returning * into v_row;
    end if;
    return v_row;
  end if;

  insert into public.ram_brands (name)
  values (v_name)
  on conflict (name) do update set active = true, updated_at = now()
  returning * into v_row;

  return v_row;
end;
$$;

revoke all on function public.ram_ensure_brand(text) from public;
grant execute on function public.ram_ensure_brand(text) to authenticated;

